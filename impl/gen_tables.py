#!/usr/bin/env python3
"""Generate the constant tables used by the fast_const and ct variants.

  impl/fast_const_tables.h  SB2, SB2I, PT, PTI as `const` arrays, built with the
                            same formulas as init_fast() in dipper_fast.c
                            (byte equality is checked by impl/check_tables.c)
  impl/ct_perm.h            the Dipper (= GIFT-64) bit permutation as a fixed
                            list of (mask, shift) pairs, no table lookups

Usage: python3 impl/gen_tables.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
S = [0x1, 0xA, 0x4, 0xC, 0x6, 0xF, 0x3, 0x9, 0x2, 0xD, 0xB, 0x7, 0x5, 0x0, 0x8, 0xE]
SI = [0xD, 0x0, 0x8, 0x6, 0x2, 0xC, 0x4, 0xB, 0xE, 0x7, 0x1, 0xA, 0x3, 0x9, 0xF, 0x5]


def perm(i):
    return 4 * (i // 16) + 16 * ((3 * ((i % 16) // 4) + (i % 4)) % 4) + (i % 4)


P = [perm(i) for i in range(64)]
PINV = [0] * 64
for i, p in enumerate(P):
    PINV[p] = i
assert sorted(P) == list(range(64))

# --- fast_const tables (same formulas as init_fast) ---
SB2 = [S[b & 0xF] | (S[(b >> 4) & 0xF] << 4) for b in range(256)]
SB2I = [SI[b & 0xF] | (SI[(b >> 4) & 0xF] << 4) for b in range(256)]
PT = [[0] * 16 for _ in range(16)]
PTI = [[0] * 16 for _ in range(16)]
for j in range(16):
    for v in range(16):
        w = wi = 0
        for k in range(4):
            if (v >> k) & 1:
                w |= 1 << P[4 * j + k]
                wi |= 1 << PINV[4 * j + k]
        PT[j][v] = w
        PTI[j][v] = wi


def u16_rows(vals):
    return ",\n".join("    " + ",".join("0x%04X" % x for x in vals[r:r + 8])
                      for r in range(0, len(vals), 8))


def u64_rows(tab):
    out = []
    for row in tab:
        out.append("    {" + ",".join("0x%016XULL" % x for x in row) + "}")
    return ",\n".join(out)


hdr = """/* GENERATED by impl/gen_tables.py -- do not edit.
 * Same contents as the tables built at run time by init_fast() in dipper_fast.c,
 * but as const arrays (flash on MCUs). Checked by impl/check_tables.c. */
#ifndef FAST_CONST_TABLES_H
#define FAST_CONST_TABLES_H
#include <stdint.h>
static const uint16_t SB2C[256] = {
%s
};
static const uint16_t SB2IC[256] = {
%s
};
static const uint64_t PTC[16][16] = {
%s
};
static const uint64_t PTIC[16][16] = {
%s
};
#endif
""" % (u16_rows(SB2), u16_rows(SB2I), u64_rows(PT), u64_rows(PTI))
with open(os.path.join(HERE, "fast_const_tables.h"), "w") as f:
    f.write(hdr)

# --- ct permutation: group bits by displacement d = P(i) - i ---
def groups(pmap):
    g = {}
    for i, p in enumerate(pmap):
        g[p - i] = g.get(p - i, 0) | (1 << i)
    return sorted(g.items())


def apply_groups(gs, s):
    o = 0
    for d, m in gs:
        o |= ((s & m) << d) if d >= 0 else ((s & m) >> -d)
    return o & (2**64 - 1)


def apply_table(pmap, s):
    o = 0
    for i in range(64):
        o |= ((s >> i) & 1) << pmap[i]
    return o


G, GI = groups(P), groups(PINV)
import random
rnd = random.Random(1)
for _ in range(10000):
    s = rnd.getrandbits(64)
    assert apply_groups(G, s) == apply_table(P, s)
    assert apply_groups(GI, s) == apply_table(PINV, s)
for i in range(64):
    assert apply_groups(G, 1 << i) == 1 << P[i]


def c_expr(gs):
    lines = []
    for d, m in gs:
        if d > 0:
            lines.append("((s & 0x%016XULL) << %d)" % (m, d))
        elif d < 0:
            lines.append("((s & 0x%016XULL) >> %d)" % (m, -d))
        else:
            lines.append("(s & 0x%016XULL)" % m)
    return "\n        | ".join(lines)


ct = """/* GENERATED by impl/gen_tables.py -- do not edit.
 * Dipper bit permutation (identical to GIFT-64's) as fixed masks and shifts:
 * bit i moves to P(i); bits with the same displacement P(i)-i share one mask.
 * %d masks for P, %d for P^-1. Checked against the bit-loop definition for all
 * 64 unit vectors and 10^4 random states by the generator. */
#ifndef CT_PERM_H
#define CT_PERM_H
#include <stdint.h>
static inline uint64_t ct_perm(uint64_t s){
    return  %s;
}
static inline uint64_t ct_perm_inv(uint64_t s){
    return  %s;
}
#endif
""" % (len(G), len(GI), c_expr(G), c_expr(GI))
with open(os.path.join(HERE, "ct_perm.h"), "w") as f:
    f.write(ct)
print("wrote fast_const_tables.h and ct_perm.h (%d / %d masks)" % (len(G), len(GI)))
